package io.github.shoalapps.swordfish.player

import io.github.shoalapps.swordfish.AppGraph
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Request
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo

/** One line of captions on screen between [startMs] and [endMs]. */
data class Cue(val startMs: Long, val endMs: Long, val text: String)

/** A caption track; [lang] is its BCP 47 tag, e.g. "en" or "pt-BR". */
/** [translated]: YouTube's machine translation of another track, into [lang]. */
data class CaptionTrack(val label: String, val url: String, val auto: Boolean, val lang: String = "", val translated: Boolean = false)

data class Chapter(val title: String, val startMs: Long, val thumbnail: String?)

object Captions {
    /**
     * Every language YouTube offers, one track each (hand-written before auto-generated). NewPipe
     * now hands YouTube's captions over as TTML only, so both TTML and WebVTT are taken; the
     * reader below copes with either.
     */
    fun tracks(info: StreamInfo): List<CaptionTrack> =
        info.subtitles
            .filter { it.isUrl && (it.format == MediaFormat.VTT || it.format == MediaFormat.TTML) }
            .sortedBy { if (it.format == MediaFormat.VTT) 0 else 1 }
            .map {
                CaptionTrack(
                    languageName(it.languageTag, it.displayLanguageName) + if (it.isAutoGenerated) " (auto-generated)" else "",
                    it.content, it.isAutoGenerated, it.languageTag.orEmpty(),
                )
            }
            .distinctBy { it.label }
            .sortedWith(compareBy<CaptionTrack> { it.auto }.thenBy(String.CASE_INSENSITIVE_ORDER) { it.label })

    /** "German", not "Deutsch": names in the viewer's own language, like YouTube's menu. */
    private fun languageName(tag: String?, fallback: String): String {
        val locale = tag?.takeIf { it.isNotBlank() }?.let(java.util.Locale::forLanguageTag) ?: return fallback
        val viewer = java.util.Locale.getDefault()
        return locale.getDisplayName(viewer).takeIf { it.isNotBlank() && it != tag }
            ?.replaceFirstChar { it.titlecase(viewer) } ?: fallback
    }

    /**
     * When nothing's in [mine], adds YouTube's own machine translation into it, made from the
     * best track there is (hand-written first). YouTube translates any track given `tlang`.
     */
    fun withTranslation(tracks: List<CaptionTrack>, mine: String): List<CaptionTrack> {
        val lang = mine.substringBefore('-').lowercase()
        if (lang.isBlank() || tracks.isEmpty() || tracks.any { it.lang.substringBefore('-').equals(lang, true) }) return tracks
        val source = tracks.firstOrNull { !it.auto } ?: tracks.first()
        val name = java.util.Locale.forLanguageTag(lang).let { it.getDisplayName(java.util.Locale.getDefault()).replaceFirstChar { c -> c.titlecase() } }
        val sep = if ('?' in source.url) '&' else '?'
        return tracks + CaptionTrack("$name (auto-translated)", "${source.url}${sep}tlang=$lang", auto = true, lang = lang, translated = true)
    }

    /**
     * The track to turn on: the language you last picked, else the first of your own languages
     * (hand-written before auto-generated), else the auto-generated track, which is in the
     * video's own language, else the first there is.
     */
    fun preferred(tracks: List<CaptionTrack>, languages: List<String>, remembered: String?): CaptionTrack? {
        if (tracks.isEmpty()) return null
        fun base(tag: String) = tag.substringBefore('-').lowercase()
        fun inLanguage(tag: String) = tracks
            .filter { base(it.lang) == base(tag) }
            .sortedWith(compareBy<CaptionTrack> { it.auto }.thenByDescending { it.lang.equals(tag, ignoreCase = true) })
            .firstOrNull()
        remembered?.takeIf { it.isNotBlank() }?.let { r -> tracks.firstOrNull { it.lang.equals(r, true) && !it.auto } ?: inLanguage(r) }?.let { return it }
        languages.forEach { l -> inLanguage(l)?.let { return it } }
        return tracks.firstOrNull { it.auto } ?: tracks.first()
    }

    suspend fun load(track: CaptionTrack): List<Cue> = withContext(Dispatchers.IO) {
        val req = Request.Builder().url(track.url).header("User-Agent", io.github.shoalapps.swordfish.data.NewPipeDownloader.USER_AGENT).build()
        val body = AppGraph.http.newCall(req).execute().use {
            val text = it.body?.string().orEmpty()
            if (!it.isSuccessful) {
                android.util.Log.w("Captions", "HTTP ${it.code} for ${track.label}: ${text.take(200)}")
                throw java.io.IOException("Captions: HTTP ${it.code}")
            }
            text
        }
        parse(body)
    }

    /** The track a machine translation was made from: its URL without `tlang`. */
    fun untranslated(track: CaptionTrack): CaptionTrack =
        track.copy(url = track.url.replace(Regex("""[?&]tlang=[^&]*"""), ""), translated = false)

    /**
     * Translates [cues] into [to] ourselves, for when YouTube won't (it answers translated
     * requests with 429 when it wants a proof-of-origin token). [onProgress] gets the list with
     * each batch swapped in.
     */
    suspend fun translate(cues: List<Cue>, to: String, onProgress: suspend (List<Cue>) -> Unit) {
        val out = cues.toMutableList()
        io.github.shoalapps.swordfish.data.TitleTranslator.lines(cues.map { it.text }, to) { start, lines ->
            lines.forEachIndexed { k, line -> if (line.isNotBlank()) out[start + k] = out[start + k].copy(text = line) }
            onProgress(out.toList())
        }
    }

    /** Reads WebVTT or TTML, whichever [text] is. */
    fun parse(text: String): List<Cue> =
        if (text.trimStart().startsWith("WEBVTT")) parseVtt(text) else parseTtml(text)

    private val paragraph = Regex("""<p\b([^>]*)>(.*?)</p>""", RegexOption.DOT_MATCHES_ALL)
    private val attr = Regex("""([\w:]+)\s*=\s*"([^"]*)"""")
    private val lineBreak = Regex("""<br\s*/?>""")
    private val clock = Regex("""(?:(\d+):)?(\d{1,2}):(\d{2})(?:[.,](\d{1,3}))?""")
    private val offset = Regex("""([\d.]+)(h|m|s|ms|t)""")

    private fun unescape(s: String) = s.replace("&lt;", "<").replace("&gt;", ">").replace("&#39;", "'")
        .replace("&apos;", "'").replace("&quot;", "\"").replace("&nbsp;", " ").replace("&amp;", "&")

    /** A TTML time: "00:01:02.500", "1.5s", "2500ms" or "30000000t" (ticks at [tickRate] a second). */
    private fun ttmlTime(v: String, tickRate: Double): Long? {
        clock.matchEntire(v.trim())?.let { m ->
            val (h, mm, ss, f) = m.destructured
            return ((h.toLongOrNull() ?: 0) * 3600 + mm.toLong() * 60 + ss.toLong()) * 1000 + f.padEnd(3, '0').ifEmpty { "0" }.toLong()
        }
        val m = offset.matchEntire(v.trim()) ?: return null
        val n = m.groupValues[1].toDoubleOrNull() ?: return null
        return when (m.groupValues[2]) {
            "h" -> n * 3_600_000; "m" -> n * 60_000; "s" -> n * 1000; "ms" -> n; else -> n / tickRate * 1000
        }.toLong()
    }

    fun parseTtml(text: String): List<Cue> {
        val tickRate = Regex("""tickRate\s*=\s*"(\d+)"""").find(text)?.groupValues?.get(1)?.toDoubleOrNull() ?: 10_000_000.0
        return paragraph.findAll(text).mapNotNull { p ->
            val a = attr.findAll(p.groupValues[1]).associate { it.groupValues[1] to it.groupValues[2] }
            val start = a["begin"]?.let { ttmlTime(it, tickRate) } ?: return@mapNotNull null
            val end = a["end"]?.let { ttmlTime(it, tickRate) } ?: a["dur"]?.let { d -> ttmlTime(d, tickRate)?.let { start + it } } ?: return@mapNotNull null
            val body = unescape(p.groupValues[2].replace(lineBreak, "\n").replace(tags, "")).replace(tags, "")
                .lines().map { it.trim() }.filter { it.isNotEmpty() }.joinToString("\n")
            if (body.isEmpty() || end <= start) null else Cue(start, end, body)
        }.toList()
    }

    private val timeLine = Regex("""(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})\s+-->\s+(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})""")
    private val tags = Regex("""<[^>]+>""")

    private fun ms(h: String?, m: String, s: String, f: String) =
        ((h?.trimEnd(':')?.toLongOrNull() ?: 0) * 3600 + m.toLong() * 60 + s.toLong()) * 1000 + f.toLong()

    /**
     * Small WebVTT reader. YouTube's auto-captions repeat the previous line in each cue,
     * so only the newest line of each cue is kept for those.
     */
    fun parseVtt(text: String): List<Cue> {
        val cues = mutableListOf<Cue>()
        val lines = text.replace("\r", "").split("\n")
        var i = 0
        while (i < lines.size) {
            val m = timeLine.find(lines[i])
            if (m == null) { i++; continue }
            val g = m.groupValues
            val start = ms(g[1].ifEmpty { null }, g[2], g[3], g[4])
            val end = ms(g[5].ifEmpty { null }, g[6], g[7], g[8])
            i++
            val body = mutableListOf<String>()
            while (i < lines.size && lines[i].isNotBlank()) {
                // Strip tags, unescape, strip again: YouTube escapes its styling ("&lt;i&gt;").
                body += lines[i].replace(tags, "").replace("&gt;", ">").replace("&lt;", "<").replace("&#39;", "'").replace("&quot;", "\"").replace("&amp;", "&").replace(tags, "").trim()
                i++
            }
            val clean = body.filter { it.isNotBlank() }
            if (clean.isNotEmpty() && end - start > 20) cues += Cue(start, end, clean.joinToString("\n"))
        }
        // Collapse the rolling style of auto-captions: drop a leading line repeated from the previous cue.
        val out = mutableListOf<Cue>()
        for (c in cues) {
            val prev = out.lastOrNull()
            val lines2 = c.text.split("\n")
            val text2 = if (prev != null && lines2.size > 1 && lines2.first() == prev.text.split("\n").last()) {
                lines2.drop(1).joinToString("\n")
            } else c.text
            out += c.copy(text = text2)
        }
        return out
    }
}

object Chapters {
    fun of(info: StreamInfo): List<Chapter> =
        info.streamSegments
            .map { Chapter(it.title ?: "", it.startTimeSeconds * 1000L, it.previewUrl) }
            .sortedBy { it.startMs }
}

/** Sleep timer choices in minutes; -1 means "end of video". */
val sleepChoices = listOf(0, 10, 15, 20, 30, 45, 60, -1)
